"""Builds src/data.js and src/sprites.js from PokéAPI CSVs and sprites.

Usage: python3 build_data.py <csv_dir> <sprite_cache_dir> <out_src_dir>
Pool: Gen 1-4 (species id <= 493), fully evolved within Gen 1-4, default forms.
Legendary and mythical Pokémon are included but flagged.
"""
import base64, csv, io, json, os, sys, urllib.request
from PIL import Image

csv_dir, sprite_dir, out_dir = sys.argv[1:4]
MAX_ID = 493

def rows(name):
    with open(os.path.join(csv_dir, name + '.csv'), newline='', encoding='utf-8') as f:
        return list(csv.DictReader(f))

species = {int(r['id']): r for r in rows('pokemon_species') if int(r['id']) <= MAX_ID}
has_child = {int(r['evolves_from_species_id']) for r in species.values() if r['evolves_from_species_id']}
names = {int(r['pokemon_species_id']): r['name'] for r in rows('pokemon_species_names') if r['local_language_id'] == '9'}
pokemon = {int(r['id']): r for r in rows('pokemon') if r['is_default'] == '1' and int(r['species_id']) <= MAX_ID}
STAT = {'1': 'hp', '2': 'atk', '3': 'def', '4': 'spa', '5': 'spd', '6': 'spe'}
stats, types, abil = {}, {}, {}
for r in rows('pokemon_stats'):
    pid = int(r['pokemon_id'])
    if pid in pokemon and r['stat_id'] in STAT:
        stats.setdefault(pid, {})[STAT[r['stat_id']]] = int(r['base_stat'])
type_names = {r['id']: r['identifier'] for r in rows('types')}
for r in sorted(rows('pokemon_types'), key=lambda r: int(r['slot'])):
    pid = int(r['pokemon_id'])
    if pid in pokemon:
        types.setdefault(pid, []).append(type_names[r['type_id']].capitalize())
ability_names = {r['ability_id']: r['name'] for r in rows('ability_names') if r['local_language_id'] == '9'}
for r in sorted(rows('pokemon_abilities'), key=lambda r: int(r['slot'])):
    pid = int(r['pokemon_id'])
    if pid in pokemon and r['is_hidden'] == '0':
        abil.setdefault(pid, []).append(ability_names[r['ability_id']])

out, sprites = [], {}
os.makedirs(sprite_dir, exist_ok=True)
for pid, p in sorted(pokemon.items()):
    sid = int(p['species_id'])
    s = species[sid]
    if sid in has_child:
        continue
    gen = int(s['generation_id'])
    out.append({
        'id': pid, 'name': names[sid], 'gen': gen, 'types': types[pid], 'stats': stats[pid],
        'height': int(p['height']), 'weight': int(p['weight']), 'abilities': abil.get(pid, []),
        'legendary': s['is_legendary'] == '1' or s['is_mythical'] == '1',
    })
    path = os.path.join(sprite_dir, f'{pid}.png')
    if not os.path.exists(path):
        url = f'https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/{pid}.png'
        with urllib.request.urlopen(url) as resp, open(path, 'wb') as f:
            f.write(resp.read())
    img = Image.open(path).convert('RGBA')
    bbox = img.getchannel('A').getbbox()
    if bbox:
        img = img.crop(bbox)
    buf = io.BytesIO()
    img.save(buf, 'PNG', optimize=True)
    sprites[pid] = 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()

with open(os.path.join(out_dir, 'data.js'), 'w') as f:
    f.write('// Generated by build/build_data.py from PokéAPI data. Do not edit.\n')
    f.write('export const POKEMON = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
with open(os.path.join(out_dir, 'sprites.js'), 'w') as f:
    f.write('// Generated by build/build_data.py from PokéAPI sprites. Do not edit.\n')
    f.write('export const SPRITES = ' + json.dumps(sprites, separators=(',', ':')) + ';\n')
print(len(out), 'pokemon;', sum(1 for p in out if p['legendary']), 'legendary')
