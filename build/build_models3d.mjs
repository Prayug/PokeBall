// Downloads, converts and packs the 3D Pokémon models.
//
//   npm i --no-save @gltf-transform/core@4 @gltf-transform/extensions@4 @gltf-transform/functions@4 draco3dgltf meshoptimizer sharp
//   node build/build_models3d.mjs <cache_dir>
//
// Source: the Pokémon 3D API asset collection, models/opt/regular/<id>.glb in
// github.com/Pokemon-3D-api/assets (fan-extracted official game models gathered from Sketchfab;
// Draco geometry, WebP textures). For each Pokémon in src/data.js this keeps one clip per role
// (idle, run, walk, attack, damage, down, glad), renamed to the role, shrinks textures to 512px,
// re-compresses geometry and animation with meshopt (its decoder is small enough to bundle,
// unlike Draco's), then writes dist/models3d/<chunk>.js (two models per file, base64, so the
// page also works opened from disk) and src/models3d.js, the index the game reads.
import fs from 'fs';
import path from 'path';
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { prune, dedup, textureCompress, meshopt, resample } from '@gltf-transform/functions';
import draco3d from 'draco3dgltf';
import { MeshoptEncoder, MeshoptDecoder } from 'meshoptimizer';
import sharp from 'sharp';
import { POKEMON } from '../src/data.js';

const cache = process.argv[2];
if (!cache) { console.error('usage: node build/build_models3d.mjs <cache_dir>'); process.exit(1); }
const RAW = path.join(cache, 'raw'), OUT = path.join(cache, 'out');
fs.mkdirSync(RAW, { recursive: true }); fs.mkdirSync(OUT, { recursive: true });
const BASE = 'https://raw.githubusercontent.com/Pokemon-3D-api/assets/main/models/opt/regular/';

// 1. Download (gender-split species are stored as <id>-M).
async function download(id) {
  const f = path.join(RAW, `${id}.glb`);
  if (fs.existsSync(f)) return true;
  for (const name of [id, `${id}-M`]) {
    const r = await fetch(`${BASE}${name}.glb`);
    if (r.ok) { fs.writeFileSync(f, Buffer.from(await r.arrayBuffer())); return true; }
  }
  return false;
}
const ids = POKEMON.map((p) => p.id);
const have = [];
for (let i = 0; i < ids.length; i += 8) {
  const got = await Promise.all(ids.slice(i, i + 8).map(download));
  got.forEach((ok, k) => { if (ok) have.push(ids[i + k]); });
}
console.log(`${have.length} of ${ids.length} Pokémon have a model`);

// 2. Convert.
await MeshoptEncoder.ready; await MeshoptDecoder.ready;
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({
  'draco3d.decoder': await draco3d.createDecoderModule(), 'meshopt.encoder': MeshoptEncoder, 'meshopt.decoder': MeshoptDecoder });
const ROLES = [
  ['idle', [/_0\d{4}_defaultwait01_loop$/, /defaultwait01_loop$/, /battlewait01_loop$/, /(^|\|)(idle|idol)$/i]],
  ['run', [/_0\d{4}_run01_loop$/, /run01_loop$/, /(^|\|)bd_run$/i]],
  ['walk', [/_0\d{4}_walk01_loop$/, /walk01_loop$/, /(^|\|)walking$/i]],
  ['attack', [/_2\d{4}_attack01$/, /attack01$/, /rangeattack01$/, /(^|\|)attack$/i]],
  ['damage', [/_2\d{4}_damage01$/, /damage01$/]],
  ['down', [/_2\d{4}_down01_loop$/, /down01_loop$/, /(^|\|)faint$/i]],
  ['glad', [/glad01$/, /_0\d{4}_roar01$/, /roar01$/]],
];
for (const id of have) {
  const out = path.join(OUT, `${id}.glb`);
  if (fs.existsSync(out)) continue;
  const doc = await io.read(path.join(RAW, `${id}.glb`));
  const r = doc.getRoot();
  const all = r.listAnimations(), keep = new Map();
  for (const [role, pats] of ROLES) {
    for (const p of pats) { const a = all.find((x) => p.test(x.getName()) && ![...keep.values()].includes(x)); if (a) { keep.set(role, a); break; } }
  }
  if (!keep.size && all.length) keep.set('idle', all[0]);
  for (const a of all) {
    if ([...keep.values()].includes(a)) continue;
    for (const c of a.listChannels()) c.dispose();
    for (const s of a.listSamplers()) s.dispose();
    a.dispose();
  }
  for (const [role, a] of keep) a.setName(role);
  r.listExtensionsUsed().find((e) => e.extensionName === 'KHR_draco_mesh_compression')?.dispose();
  await doc.transform(resample(), prune(), dedup(),
    textureCompress({ encoder: sharp, targetFormat: 'webp', resize: [512, 512], quality: 82 }),
    meshopt({ encoder: MeshoptEncoder, level: 'medium' }));
  await io.write(out, doc);
}

// 3. Pack two per file, and write the index.
const dist = path.resolve('dist/models3d');
fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(dist, { recursive: true });
const index = {};
const sorted = [...have].sort((a, b) => a - b);
for (let i = 0; i < sorted.length; i += 2) {
  const c = i / 2, part = {};
  for (const id of sorted.slice(i, i + 2)) { part[id] = fs.readFileSync(path.join(OUT, `${id}.glb`)).toString('base64'); index[id] = c; }
  fs.writeFileSync(path.join(dist, `${c}.js`), `__pbModels(${JSON.stringify(part)});\n`);
}
fs.writeFileSync('src/models3d.js', `// Generated by build/build_models3d.mjs: Pokémon id -> models3d/<chunk>.js. Do not edit.\nexport const MODEL_INDEX = ${JSON.stringify(index)};\n`);
console.log(`wrote ${Math.ceil(sorted.length / 2)} files to dist/models3d`);
